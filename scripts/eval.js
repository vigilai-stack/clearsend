// Runs the rules-only pre-check over the synthetic set and writes docs/EVAL.md.
// Fails (exit 1) if any red-flag message is missed or any planted "never send"
// item survives into the outgoing text.
import { readFileSync, writeFileSync } from 'node:fs';
import { precheck } from '../src/precheck.js';

const rows = JSON.parse(readFileSync(new URL('../data/synthetic-messages.json', import.meta.url)));
let flagged = 0, flaggedHit = 0, calm = 0, falseAlarm = 0, planted = 0, removed = 0, catOk = 0, levelExact = 0;
const misses = [];
for (const r of rows) {
  const out = await precheck(r.text);
  if (r.level !== 'none') {
    flagged++;
    if (out.level !== 'none') flaggedHit++; else misses.push(`${r.id}: missed red flag`);
  } else {
    calm++;
    if (out.level !== 'none') { falseAlarm++; misses.push(`${r.id}: false alarm (${out.level})`); }
  }
  if (out.level === r.level) levelExact++;
  for (const p of r.planted) {
    planted++;
    if (out.removed.some((f) => f.id === p)) removed++; else misses.push(`${r.id}: ${p} not removed`);
  }
  if (out.category === r.category) catOk++;
}
const pct = (a, b) => (b ? ((100 * a) / b).toFixed(1) : 'n/a');
const md = `# Evaluation (rules only, synthetic messages)

Generated by \`npm run eval\`. ${rows.length} made-up portal messages in \`data/synthetic-messages.json\`. No real patient data.

| Check | Result |
|---|---|
| Red-flag messages caught | ${flaggedHit} / ${flagged} (${pct(flaggedHit, flagged)}%) |
| Exact level (none / urgent / emergency / crisis) | ${levelExact} / ${rows.length} |
| False alarms on calm messages | ${falseAlarm} / ${calm} |
| Planted "never send" items removed | ${removed} / ${planted} (${pct(removed, planted)}%) |
| Category matches the label (keyword fallback only) | ${catOk} / ${rows.length} (${pct(catOk, rows.length)}%) |

${misses.length ? 'Notes:\n\n' + misses.map((m) => '- ' + m).join('\n') : 'No misses.'}

The category score is the keyword fallback alone. In the app, the on-device model picks the category when Chrome's built-in model is available; the red-flag and removal checks above never depend on the model.
`;
writeFileSync(new URL('../docs/EVAL.md', import.meta.url), md);
console.log(md);
const hardFail = flaggedHit < flagged || removed < planted;
process.exit(hardFail ? 1 : 0);
